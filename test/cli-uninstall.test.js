import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";

import { createTemporaryDirectory, runCommand } from "./helpers/command-fixtures.js";

const binPath = fileURLToPath(new URL("../bin/vasir.js", import.meta.url));
const trackedSkill = ".agents/skills/tracked";
const statePath = ".agents/vasir-install-state.json";
const configPath = ".agents/vasir.json";
const generatedHeader = "<!-- Generated by Vasir. Put project-specific policy in AGENTS__non-obvious.md and run vasir agents sync. -->";

function write(root, relativePath, contents) {
  const filePath = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function read(root, relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

function exists(root, relativePath) {
  return Boolean(fs.lstatSync(path.join(root, relativePath), { throwIfNoEntry: false }));
}

function createFixture(root) {
  write(root, trackedSkill + "/SKILL.md", "# Modified installed skill\n");
  write(root, configPath, JSON.stringify({ schemaVersion: 1, tracking: { mode: "selected", skillNames: ["tracked"] } }));
  write(root, statePath, JSON.stringify({
    schemaVersion: 3,
    skills: { tracked: { managedFiles: ["SKILL.md"], fileHashes: { "SKILL.md": "original hash" } } }
  }));
}

function uninstall(cwd, args, errorCode = null) {
  const result = runCommand(process.execPath, [binPath, "uninstall", ...args, "--json"], cwd);
  if (errorCode) {
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.equal(result.stdout, "");
    const payload = JSON.parse(result.stderr);
    assert.equal(payload.code, errorCode, result.stderr);
    return payload;
  }
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(result.stderr, "");
  const payload = JSON.parse(result.stdout);
  assert.equal(payload.command, "uninstall");
  assert.equal(payload.status, "success");
  return payload;
}

function linkDirectory(root, link, target) {
  const linkPath = path.join(root, link);
  fs.mkdirSync(path.dirname(linkPath), { recursive: true });
  fs.symlinkSync(target, linkPath, process.platform === "win32" ? "junction" : "dir");
}

test("uninstall dry-run infers the Git project root and leaves local state untouched", (testContext) => {
  const root = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-dry-"));
  createFixture(root);
  fs.mkdirSync(path.join(root, ".git"));
  write(root, "src/index.js", "export {};\n");
  const before = read(root, statePath);
  const result = uninstall(path.join(root, "src"), ["--dry-run"]);
  assert.equal(result.dryRun, true);
  const [project] = result.projects;
  assert.equal(project.projectRootDirectory, root);
  assert.deepEqual(project.entries, [
    { path: trackedSkill, action: "move" },
    { path: configPath, action: "move" },
    { path: statePath, action: "move" }
  ]);
  assert.equal(project.backupDirectory, null);
  assert.deepEqual(project.completedPaths, []);
  assert.equal(exists(root, ".vasir-backups"), false);
  assert.equal(read(root, statePath), before);
  assert.equal(read(root, trackedSkill + "/SKILL.md"), "# Modified installed skill\n");
});

test("uninstall backs up edited tracked files and generated contracts across a deduplicated batch", (testContext) => {
  const base = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-batch-"));
  const first = path.join(base, "first project");
  const second = path.join(base, "second project");
  createFixture(first);
  createFixture(second);
  write(first, "AGENTS.md", "# Generated project contract\n" + generatedHeader + "\n");
  write(first, "AGENTS__non-obvious.md", "Custom project rules\n");
  write(first, "CLAUDE.md", "Authored Claude contract\n");
  write(first, ".agents/skills/custom/SKILL.md", "Local skill\n");
  write(first, ".agents/vasir-evals/tracked/run-1/run.json", "{}\n");
  write(first, ".agents/notes.md", "Local notes\n");
  write(first, ".claude/settings.json", "{}\n");
  write(first, ".codex/skills/other/SKILL.md", "Host skill\n");

  const result = uninstall(base, ["first project", second, first]);
  assert.equal(result.dryRun, false);
  assert.deepEqual(result.projects.map((project) => project.projectRootDirectory), [first, second]);
  for (const project of result.projects) {
    assert.equal(path.dirname(project.backupDirectory), path.join(project.projectRootDirectory, ".vasir-backups"));
    assert.equal(exists(project.projectRootDirectory, trackedSkill), false);
    assert.equal(exists(project.projectRootDirectory, configPath), false);
    assert.equal(exists(project.projectRootDirectory, statePath), false);
    assert.equal(read(project.backupDirectory, trackedSkill + "/SKILL.md"), "# Modified installed skill\n");
    const manifest = JSON.parse(read(project.backupDirectory, "manifest.json"));
    assert.deepEqual(manifest.entries, project.entries);
    assert.deepEqual(project.completedPaths, manifest.entries.map((entry) => entry.path));
  }

  const firstProject = result.projects[0];
  assert.match(read(firstProject.backupDirectory, "AGENTS.md"), /Generated project contract/);
  assert.equal(read(firstProject.backupDirectory, "AGENTS__non-obvious.md"), "Custom project rules\n");
  assert.equal(read(firstProject.backupDirectory, ".agents/vasir-evals/tracked/run-1/run.json"), "{}\n");
  assert.equal(exists(first, ".agents/vasir-evals"), false);
  assert(firstProject.completedPaths.indexOf("AGENTS__non-obvious.md") < firstProject.completedPaths.indexOf("AGENTS.md"));
  assert.deepEqual(firstProject.preservedPaths, [
    ".agents/notes.md", ".agents/skills/custom", ".claude/settings.json", ".codex/skills", "CLAUDE.md"
  ]);
  assert.equal(read(first, "CLAUDE.md"), "Authored Claude contract\n");
  assert.equal(read(first, ".agents/skills/custom/SKILL.md"), "Local skill\n");
  assert.equal(read(first, ".codex/skills/other/SKILL.md"), "Host skill\n");

  const backupsBefore = fs.readdirSync(path.join(first, ".vasir-backups"));
  const repeat = uninstall(base, ["--repo-root", "first project"]).projects[0];
  assert.equal(repeat.backupDirectory, null);
  assert.deepEqual(repeat.entries, []);
  assert.deepEqual(fs.readdirSync(path.join(first, ".vasir-backups")), backupsBefore);
});

test("uninstall preflights a whole batch and refuses ambiguous ownership and overlapping roots", (testContext) => {
  const base = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-preflight-"));
  const first = path.join(base, "first");
  const second = path.join(base, "second");
  createFixture(first);
  write(second, configPath, "{}");
  write(second, ".agents/skills/custom/SKILL.md", "Local skill\n");
  uninstall(base, ["first", "second"], "UNINSTALL_OWNERSHIP_UNKNOWN");
  uninstall(base, ["first", "missing"], "PROJECT_ROOT_NOT_FOUND");
  uninstall(base, ["first", "first/.agents"], "OVERLAPPING_UNINSTALL_TARGETS");
  uninstall(base, ["first", "--repo-root", "second"], "INVALID_UNINSTALL_TARGETS");
  uninstall(base, ["--repo-root", "first", "--repo-root", "second"], "INVALID_UNINSTALL_TARGETS");
  uninstall(first, [""], "INVALID_UNINSTALL_TARGETS");
  assert.equal(exists(first, ".vasir-backups"), false);
  assert.equal(exists(first, trackedSkill), true);
  assert.equal(exists(second, configPath), true);

  fs.unlinkSync(path.join(second, configPath));
  write(second, "AGENTS.md", "# Generated\n" + generatedHeader + "\n");
  uninstall(base, ["first", "second"], "UNINSTALL_OWNERSHIP_UNKNOWN");
  assert.equal(exists(first, ".vasir-backups"), false);
  assert.equal(exists(second, "AGENTS.md"), true);
});

test("uninstall refuses malformed state, path traversal, and Windows stream paths", (testContext) => {
  const root = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-invalid-"));
  createFixture(root);
  write(root, "victim/SKILL.md", "Outside managed skills\n");
  const validEntry = { managedFiles: [], fileHashes: {} };
  for (const contents of [
    "{",
    JSON.stringify({ schemaVersion: 3, skills: { "../../victim": validEntry } }),
    JSON.stringify({ schemaVersion: 3, skills: { "..\\..\\victim": validEntry } }),
    JSON.stringify({ schemaVersion: 3, skills: { "name:stream": validEntry } }),
    JSON.stringify({ schemaVersion: 3, skills: { tracked: { ...validEntry, managedFiles: ["../victim"] } } })
  ]) {
    write(root, statePath, contents);
    uninstall(root, ["--dry-run"], "INVALID_PROJECT_INSTALL_STATE");
    assert.equal(read(root, statePath), contents);
    assert.equal(exists(root, ".vasir-backups"), false);
    assert.equal(read(root, "victim/SKILL.md"), "Outside managed skills\n");
  }
});

test("uninstall unlinks owned aliases and preserves external links and their targets", (testContext) => {
  const base = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-aliases-"));
  const root = path.join(base, "project");
  const external = path.join(base, "external");
  createFixture(root);
  write(external, "SKILL.md", "External files\n");
  linkDirectory(
    root,
    ".claude/skills",
    process.platform === "win32" ? path.join(root, ".agents/skills") : "../.agents/./skills/"
  );
  linkDirectory(root, ".codex/skills", external);
  linkDirectory(root, ".agents/skills/custom-link", external);
  const target = fs.readlinkSync(path.join(root, ".claude/skills"));

  const [project] = uninstall(base, ["project"]).projects;
  assert.equal(exists(root, ".claude/skills"), false);
  assert.equal(exists(root, ".codex/skills"), true);
  assert.equal(exists(root, ".agents/skills/custom-link"), true);
  assert.equal(read(external, "SKILL.md"), "External files\n");
  assert(project.preservedPaths.includes(".codex/skills"));
  assert(project.preservedPaths.includes(".agents/skills/custom-link"));
  const manifest = JSON.parse(read(project.backupDirectory, "manifest.json"));
  assert.deepEqual(manifest.entries[0], { path: ".claude/skills", action: "unlink", target });
});

test("uninstall rejects linked project, skill-tree, and backup ancestors", (testContext) => {
  const base = fs.realpathSync.native(createTemporaryDirectory(testContext, "vasir-uninstall-links-"));
  const external = path.join(base, "external");
  const first = path.join(base, "first");
  createFixture(external);
  createFixture(first);
  linkDirectory(base, "linked-root", external);
  linkDirectory(first, ".vasir-backups", external);
  linkDirectory(base, "linked-agents/.agents", path.join(external, ".agents"));
  linkDirectory(base, "linked-skills/.agents/skills", path.join(external, ".agents/skills"));
  uninstall(base, ["linked-root"], "UNSAFE_UNINSTALL_PATH");
  uninstall(base, ["first", "--dry-run"], "UNSAFE_UNINSTALL_PATH");
  uninstall(base, ["linked-agents"], "UNSAFE_UNINSTALL_PATH");
  uninstall(base, ["linked-skills"], "UNSAFE_UNINSTALL_PATH");
  assert.equal(exists(external, trackedSkill), true);
  assert.equal(exists(first, trackedSkill), true);
  assert.equal(exists(external, ".vasir-backups"), false);
});

